export const translations: Record<Language, Strings> = { en, da, de, fr, es };

/** Replaces {placeholders}: fmt("Hi {name}", { name: "Bo" }) */
export function fmt(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Picks the best supported language from the device settings. */
export function detectLanguage(): Language {
  const candidates = typeof navigator !== "undefined" ? [...(navigator.languages ?? []), navigator.language] : [];
  for (const tag of candidates) {
    const base = (tag || "").toLowerCase().split("-")[0];
    if ((LANGUAGES as string[]).includes(base)) return base as Language;
  }
  return "en";
}
